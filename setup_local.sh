#!/usr/bin/env bash
# setup_local.sh — generates real secrets for a local/offline NaijaSensei
# deployment (docker-compose.local.yml) and writes them to .env.local.
#
# Safe to re-run: if .env.local already exists, it's left untouched rather
# than silently overwritten (which would lock out anyone already using the
# admin password, and orphan the encrypted credentials in the DB).
#
# Usage:
#   ./setup_local.sh
#   docker compose --env-file .env.local -f docker-compose.local.yml up -d

set -euo pipefail

ENV_FILE=".env.local"

if [ -f "$ENV_FILE" ]; then
    echo "$ENV_FILE already exists — leaving it untouched."
    echo "(Delete it first if you genuinely want to regenerate secrets — this"
    echo " invalidates every existing login session and admin password.)"
    exit 0
fi

gen_secret() {
    python3 -c "import secrets; print(secrets.token_hex(32))"
}

JWT_SECRET_KEY="$(gen_secret)"
CREDENTIALS_ENCRYPTION_KEY="$(gen_secret)"
POSTGRES_PASSWORD="$(gen_secret)"
# Admin password is shorter and shown to a human to actually log into the
# admin panel with — a full 64-char hex string is needlessly painful to
# type/read off a screen for that one. 16 random alphanumeric characters
# comfortably clears security.py's 12-character minimum.
ADMIN_PASSWORD="$(python3 -c "import secrets, string; print(''.join(secrets.choice(string.ascii_letters + string.digits) for _ in range(16)))")"

cat > "$ENV_FILE" <<EOF
# Generated by setup_local.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# These are REAL secrets for THIS deployment — back this file up somewhere
# safe (a password manager, not just this disk) and never commit it or
# share it outside the people who should have admin/DB access to this
# specific school's server.

JWT_SECRET_KEY=$JWT_SECRET_KEY
CREDENTIALS_ENCRYPTION_KEY=$CREDENTIALS_ENCRYPTION_KEY
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
ADMIN_PASSWORD=$ADMIN_PASSWORD

# Leave blank unless this school also wants online card/bank-transfer
# payments through Paystack — redemption codes work fully offline without
# this being set at all. See LOCAL_DEPLOYMENT.md.
PAYSTACK_SECRET_KEY=
EOF

chmod 600 "$ENV_FILE"

echo ""
echo "=========================================================="
echo " $ENV_FILE created with fresh, real secrets."
echo "=========================================================="
echo ""
echo " Admin panel password (save this now — it will not be shown again"
echo " by this script, though it stays readable in $ENV_FILE):"
echo ""
echo "   $ADMIN_PASSWORD"
echo ""
echo " Next step:"
echo "   docker compose --env-file $ENV_FILE -f docker-compose.local.yml up -d"
echo ""
echo " First startup downloads the gemma3n:e2b model (a few GB) once —"
echo " this needs internet access ONE TIME during setup. After that,"
echo " the whole deployment runs with zero internet dependency."
echo "=========================================================="